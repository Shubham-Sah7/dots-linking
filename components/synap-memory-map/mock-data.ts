export function getAllMemories(data: ClientScopeData = SYNAP_CLIENT_DATA): MemoryItem[] {
  const all: MemoryItem[] = [...data.clientLevelMemories];
  for (const cust of data.customers) {
    all.push(...cust.customerLevelMemories);
    for (const usr of cust.users) {
      all.push(...usr.memories);
    }
  }
  return all;
}

export function findMemoryById(id: string, data: ClientScopeData = SYNAP_CLIENT_DATA): MemoryItem | undefined {
  return getAllMemories(data).find((m) => m.id === id);
}

export function getAllRelationships(data: ClientScopeData = SYNAP_CLIENT_DATA): MemoryRelationship[] {
  const rels: MemoryRelationship[] = [];
  const seen = new Set<string>();

  for (const m of getAllMemories(data)) {
    for (const r of m.relationships) {
      if (!seen.has(r.id)) {
        seen.add(r.id);
        rels.push(r);
      }
    }
  }
  return rels;
}

export function getMemoryScopeHierarchy(
  memory: MemoryItem,
  data: ClientScopeData = SYNAP_CLIENT_DATA
): { clientName: string; customerName?: string; userName?: string } {
  const result = {
    clientName: data.name,
    customerName: undefined as string | undefined,
    userName: undefined as string | undefined,
  };

  if (memory.scopeType === 'client') {
    return result;
  }

  for (const cust of data.customers) {
    if (cust.customerLevelMemories.some((m) => m.id === memory.id)) {
      result.customerName = cust.name;
      return result;
    }
    for (const u of cust.users) {
      if (u.memories.some((m) => m.id === memory.id)) {
        result.customerName = cust.name;
        result.userName = u.name;
        return result;
      }
    }
  }

  return result;
}
