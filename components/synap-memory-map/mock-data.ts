export function getTruthState(mem: MemoryItem): TruthState {
  if (mem.truthState) return mem.truthState;
  if (mem.status === 'Superseded') return 'Historical';
  if (mem.status === 'Inferred') return 'Inferred';
  return 'Current Truth';
}

